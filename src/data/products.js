export const getProducts = (category) => {
  if (
    !category ||
    category === "brands" ||
    category === "all" ||
    category === "catalogue"
  ) {
    return products
  }
  if (category === "new-arrivals") {
    return products.filter(
      (product) => product.featured || product.price >= 10000,
    )
  }
  if (category === "computer-glasses") {
    return products.filter(
      (p) =>
        p.category === "computer-glasses" ||
        (p.lensOptions &&
          p.lensOptions.some(
            (l) =>
              l.toLowerCase().includes("blue") ||
              l.toLowerCase().includes("screen"),
          )) ||
        p.description.toLowerCase().includes("blue-light"),
    )
  }
  if (category === "reading-glasses") {
    return products.filter(
      (p) =>
        p.category === "reading-glasses" ||
        p.frameType === "Full Frame" ||
        p.shape === "Rectangle" ||
        p.shape === "Round" ||
        p.description.toLowerCase().includes("reading") ||
        (p.lensOptions &&
          p.lensOptions.some(
            (l) =>
              l.toLowerCase().includes("near") ||
              l.toLowerCase().includes("single"),
          )),
    )
  }
  if (category === "smart-glasses") {
    return products.filter(
      (p) =>
        p.category === "smart-glasses" ||
        p.description.toLowerCase().includes("smart") ||
        p.price >= 8000,
    )
  }
  if (category === "powered-sunglasses") {
    return products.filter(
      (p) =>
        p.category === "sunglasses" ||
        p.category === "powered-sunglasses" ||
        (p.lensOptions &&
          p.lensOptions.some(
            (l) =>
              l.toLowerCase().includes("photochromic") ||
              l.toLowerCase().includes("transition"),
          )),
    )
  }
  return products.filter((product) => product.category === category)
}
